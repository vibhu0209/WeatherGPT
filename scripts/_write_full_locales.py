LOCALES = {
    "mr": MR,
    "ta": TA,
    "gu": GU,
    "kn": KN,
    "ml": ML,
    "pa": PA,
    "or": OR_,
}


def write_locale(locale: str, table: dict[str, str]) -> None:
    missing = [k for k in KEYS if k not in table]
    extra = [k for k in table if k not in KEYS]
    if missing:
        raise SystemExit(f"{locale}: missing {missing}")
    if extra:
        raise SystemExit(f"{locale}: extra {extra}")
    lines = ["<resources>"]
    for key in KEYS:
        value = table[key].replace("'", "\\'")
        lines.append(f'    <string name="{key}">{value}</string>')
    lines.append("</resources>")
    lines.append("")
    path = RES / f"values-{locale}" / "strings.xml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {path} ({len(KEYS)} keys)")


def main() -> None:
    for locale, table in LOCALES.items():
        write_locale(locale, table)


if __name__ == "__main__":
    main()
